const { Pool } = require("@neondatabase/serverless");

const ID_TABLES = new Set([
  "audit_log",
  "client_services",
  "clients",
  "inquiries",
  "notification_deliveries",
  "notifications",
  "products",
  "sale_items",
  "sales",
  "services",
  "suppliers",
  "supply_order_items",
  "supply_orders",
]);

const NUMERIC_COLUMNS = new Set([
  "active",
  "active_service_count",
  "client_count",
  "client_id",
  "count",
  "default_price_cents",
  "entity_id",
  "id",
  "is_read",
  "item_count",
  "lifetime_revenue_cents",
  "month_revenue_cents",
  "notification_id",
  "open_inquiry_count",
  "paid_sale_count",
  "price_cents",
  "priority_inquiry_count",
  "product_id",
  "quantity",
  "revenue_cents",
  "sale_id",
  "sales_count",
  "service_id",
  "stock_quantity",
  "total_cents",
  "track_inventory",
  "unit_cost_cents",
  "unit_price_cents",
  "units",
  "units_sold",
  "unread_notification_count",
]);

function normalizeRows(rows) {
  return rows.map((row) => Object.fromEntries(
    Object.entries(row).map(([key, value]) => [
      key,
      NUMERIC_COLUMNS.has(key) && typeof value === "string" && /^-?\d+$/.test(value)
        ? Number(value)
        : value,
    ]),
  ));
}

function postgresSql(sql) {
  let index = 0;
  return sql
    .replace(/\bGROUP_CONCAT\s*\(/gi, "STRING_AGG(")
    .replace(/\?/g, () => `$${++index}`);
}

function withReturningId(sql) {
  const match = sql.match(/^\s*INSERT\s+INTO\s+([a-z_]+)/i);
  if (!match || !ID_TABLES.has(match[1].toLowerCase()) || /\bRETURNING\b/i.test(sql)) return sql;
  return `${sql.trimEnd()} RETURNING id`;
}

class SqliteAdapter {
  constructor(database) {
    this.kind = "sqlite";
    this.native = database;
  }

  prepare(sql) {
    const statement = this.native.prepare(sql);
    return {
      get: async (...params) => statement.get(...params),
      all: async (...params) => statement.all(...params),
      run: async (...params) => statement.run(...params),
    };
  }

  async transaction(work) {
    this.native.exec("BEGIN IMMEDIATE");
    try {
      const result = await work(this);
      this.native.exec("COMMIT");
      return result;
    } catch (error) {
      this.native.exec("ROLLBACK");
      throw error;
    }
  }

  close() {
    this.native.close();
  }
}

class PostgresAdapter {
  constructor(pool) {
    this.kind = "postgres";
    this.pool = pool;
  }

  prepare(sql) {
    const query = postgresSql(sql);
    return {
      get: async (...params) => {
        const result = await this.pool.query(query, params);
        return normalizeRows(result.rows)[0];
      },
      all: async (...params) => {
        const result = await this.pool.query(query, params);
        return normalizeRows(result.rows);
      },
      run: async (...params) => {
        const result = await this.pool.query(withReturningId(query), params);
        const row = normalizeRows(result.rows)[0];
        return { changes: result.rowCount || 0, lastInsertRowid: row?.id };
      },
    };
  }

  async exec(sql) {
    const statements = sql.split(";").map((statement) => statement.trim()).filter(Boolean);
    for (const statement of statements) await this.pool.query(statement);
  }

  async transaction(work) {
    const client = await this.pool.connect();
    const transaction = new PostgresAdapter(client);
    try {
      await client.query("BEGIN");
      const result = await work(transaction);
      await client.query("COMMIT");
      return result;
    } catch (error) {
      await client.query("ROLLBACK");
      throw error;
    } finally {
      client.release();
    }
  }

  close() {
    return this.pool.end();
  }
}

function createPostgresDatabase(connectionString) {
  const pool = new Pool({ connectionString, max: 5 });
  return new PostgresAdapter(pool);
}

async function initializePostgresDatabase(db, defaultCurrency, services, timestamp) {
  await db.exec(`
    CREATE TABLE IF NOT EXISTS clients (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      company TEXT NOT NULL DEFAULT '',
      email TEXT NOT NULL DEFAULT '',
      phone TEXT NOT NULL DEFAULT '',
      status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paused', 'archived')),
      notes TEXT NOT NULL DEFAULT '',
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS services (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL UNIQUE,
      description TEXT NOT NULL DEFAULT '',
      default_price_cents BIGINT NOT NULL DEFAULT 0 CHECK (default_price_cents >= 0),
      active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
      created_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS client_services (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
      service_id BIGINT NOT NULL REFERENCES services(id),
      price_cents BIGINT NOT NULL DEFAULT 0 CHECK (price_cents >= 0),
      status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed', 'paused')),
      started_on TEXT NOT NULL DEFAULT '',
      notes TEXT NOT NULL DEFAULT '',
      created_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS products (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      sku TEXT NOT NULL DEFAULT '',
      price_cents BIGINT NOT NULL CHECK (price_cents >= 0),
      stock_quantity BIGINT NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
      track_inventory INTEGER NOT NULL DEFAULT 0 CHECK (track_inventory IN (0, 1)),
      active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
      created_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS sales (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      client_id BIGINT REFERENCES clients(id) ON DELETE SET NULL,
      customer_name TEXT NOT NULL DEFAULT '',
      customer_email TEXT NOT NULL DEFAULT '',
      status TEXT NOT NULL DEFAULT 'paid' CHECK (status IN ('paid', 'pending', 'refunded', 'cancelled')),
      total_cents BIGINT NOT NULL CHECK (total_cents >= 0),
      created_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS sale_items (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      sale_id BIGINT NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
      product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
      product_name TEXT NOT NULL,
      quantity BIGINT NOT NULL CHECK (quantity > 0),
      unit_price_cents BIGINT NOT NULL CHECK (unit_price_cents >= 0)
    );
    CREATE TABLE IF NOT EXISTS suppliers (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      contact_name TEXT NOT NULL DEFAULT '',
      email TEXT NOT NULL DEFAULT '',
      phone TEXT NOT NULL DEFAULT '',
      notes TEXT NOT NULL DEFAULT '',
      created_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS supply_orders (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      supplier_id BIGINT REFERENCES suppliers(id) ON DELETE SET NULL,
      status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'submitted', 'received', 'cancelled')),
      reference TEXT NOT NULL DEFAULT '',
      needed_by TEXT NOT NULL DEFAULT '',
      notes TEXT NOT NULL DEFAULT '',
      total_cents BIGINT NOT NULL DEFAULT 0 CHECK (total_cents >= 0),
      created_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS supply_order_items (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      supply_order_id BIGINT NOT NULL REFERENCES supply_orders(id) ON DELETE CASCADE,
      description TEXT NOT NULL,
      quantity BIGINT NOT NULL CHECK (quantity > 0),
      unit_cost_cents BIGINT NOT NULL DEFAULT 0 CHECK (unit_cost_cents >= 0)
    );
    CREATE TABLE IF NOT EXISTS inquiries (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      email TEXT NOT NULL,
      phone TEXT NOT NULL DEFAULT '',
      service TEXT NOT NULL DEFAULT '',
      message TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'in_progress', 'converted', 'closed')),
      priority TEXT NOT NULL DEFAULT 'normal' CHECK (priority IN ('normal', 'high', 'urgent')),
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS notifications (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title TEXT NOT NULL,
      message TEXT NOT NULL,
      priority TEXT NOT NULL DEFAULT 'normal' CHECK (priority IN ('normal', 'high', 'urgent')),
      entity_type TEXT NOT NULL DEFAULT '',
      entity_id BIGINT,
      is_read INTEGER NOT NULL DEFAULT 0 CHECK (is_read IN (0, 1)),
      created_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS notification_deliveries (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      notification_id BIGINT NOT NULL REFERENCES notifications(id) ON DELETE CASCADE,
      channel TEXT NOT NULL,
      status TEXT NOT NULL CHECK (status IN ('sent', 'failed')),
      detail TEXT NOT NULL DEFAULT '',
      created_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS push_subscriptions (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      endpoint TEXT NOT NULL UNIQUE,
      subscription_json TEXT NOT NULL,
      created_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS app_settings (
      key TEXT PRIMARY KEY,
      value TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS admin_sessions (
      token_hash TEXT PRIMARY KEY,
      csrf_hash TEXT NOT NULL,
      auth_version TEXT NOT NULL DEFAULT '',
      email TEXT NOT NULL,
      expires_at TEXT NOT NULL,
      created_at TEXT NOT NULL
    );
    ALTER TABLE admin_sessions ADD COLUMN IF NOT EXISTS auth_version TEXT NOT NULL DEFAULT '';
    CREATE TABLE IF NOT EXISTS rate_limits (
      bucket_key TEXT PRIMARY KEY,
      started_at_ms BIGINT NOT NULL,
      attempts INTEGER NOT NULL
    );
    CREATE TABLE IF NOT EXISTS audit_log (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      actor TEXT NOT NULL,
      action TEXT NOT NULL,
      entity_type TEXT NOT NULL,
      entity_id BIGINT,
      metadata_json TEXT NOT NULL DEFAULT '{}',
      created_at TEXT NOT NULL
    );
    CREATE INDEX IF NOT EXISTS idx_clients_status ON clients(status);
    CREATE INDEX IF NOT EXISTS idx_client_services_client ON client_services(client_id);
    CREATE INDEX IF NOT EXISTS idx_sales_created ON sales(created_at);
    CREATE INDEX IF NOT EXISTS idx_sales_client ON sales(client_id);
    CREATE INDEX IF NOT EXISTS idx_inquiries_created ON inquiries(created_at);
    CREATE INDEX IF NOT EXISTS idx_inquiries_status ON inquiries(status, priority);
    CREATE INDEX IF NOT EXISTS idx_notifications_created ON notifications(created_at);
  `);
  await db.prepare("INSERT INTO app_settings (key, value) VALUES ('currency', ?) ON CONFLICT (key) DO NOTHING")
    .run(defaultCurrency);
  for (const service of services) {
    await db.prepare("INSERT INTO services (name, created_at) VALUES (?, ?) ON CONFLICT (name) DO NOTHING")
      .run(service, timestamp());
  }
}

module.exports = {
  PostgresAdapter,
  SqliteAdapter,
  createPostgresDatabase,
  initializePostgresDatabase,
};
